from __future__ import annotations

import hashlib
import io
import json
import zipfile
from pathlib import Path

import pytest
from PIL import Image

from moonraker.components.file_manager import three_mf


GCODE_1 = b"; generated by OrcaSlicer 2.4.2 on 2026-01-01 at 00:00:00\nG28\nG1 X10 Y10\n"
GCODE_3 = b"; generated by OrcaSlicer 2.4.2 on 2026-01-01 at 00:00:00\nG28\nG1 X20 Y20\n"


def png_bytes(width: int, height: int) -> bytes:
    buffer = io.BytesIO()
    Image.new("RGB", (width, height), (255, 0, 0)).save(buffer, format="PNG")
    return buffer.getvalue()


def build_archive(
    path: Path,
    *,
    sliced: bool = True,
    bad_md5: bool = False,
) -> None:
    model_settings = """<?xml version="1.0" encoding="UTF-8"?>
<config>
  <plate>
    <metadata key="plater_id" value="1"/>
    <metadata key="plater_name" value="First plate"/>
    <metadata key="gcode_file" value="Metadata/plate_1.gcode"/>
    <metadata key="thumbnail_file" value="Metadata/plate_1.png"/>
    <metadata key="thumbnail_no_light_file" value="Metadata/plate_no_light_1.png"/>
    <metadata key="top_file" value="Metadata/top_1.png"/>
    <metadata key="pick_file" value="Metadata/pick_1.png"/>
  </plate>
  <plate>
    <metadata key="plater_id" value="3"/>
    <metadata key="plater_name" value="Third plate"/>
    <metadata key="gcode_file" value="Metadata/plate_3.gcode"/>
    <metadata key="thumbnail_file" value="Metadata/plate_3.png"/>
  </plate>
</config>
"""
    slice_info = """<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header>
    <header_item key="OrcaSlicer-Version" value="2.4.2"/>
  </header>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="prediction" value="123"/>
    <metadata key="weight" value="4.5"/>
    <metadata key="support_used" value="false"/>
    <warning msg="bed_temperature_too_high_than_filament" level="3" error_code="1000C001"/>
    <filament id="1" type="PLA" color="#FF0000" used_m="1.5" used_g="4.5"/>
    <object identify_id="1" name="part.stl" skipped="false"/>
  </plate>
  <plate>
    <metadata key="index" value="3"/>
    <metadata key="prediction" value="456"/>
    <metadata key="weight" value="7.5"/>
    <metadata key="support_used" value="true"/>
    <filament id="1" type="PETG" color="#00FF00" used_m="2.5" used_g="7.5"/>
    <object identify_id="2" name="part.stl" skipped="false"/>
  </plate>
</config>
"""
    project_settings = {
        "printer_model": "Test Printer",
        "printer_variant": "0.4",
        "nozzle_diameter": ["0.4"],
        "layer_height": "0.2",
        "initial_layer_print_height": "0.25",
        "nozzle_temperature_initial_layer": ["210"],
        "hot_plate_temp_initial_layer": ["60"],
        "chamber_temperature": ["40"],
        "filament_type": ["PLA"],
        "filament_colour": ["#FF0000"],
        "filament_settings_id": ["Generic PLA"],
    }
    model = """<?xml version="1.0" encoding="UTF-8"?>
<model xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">
  <metadata name="Application">OrcaSlicer-2.4.2</metadata>
</model>
"""
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("3D/3dmodel.model", model)
        archive.writestr("Metadata/model_settings.config", model_settings)
        archive.writestr("Metadata/slice_info.config", slice_info)
        archive.writestr("Metadata/project_settings.config", json.dumps(project_settings))
        archive.writestr("Metadata/plate_1.png", png_bytes(512, 512))
        archive.writestr("Metadata/plate_no_light_1.png", png_bytes(512, 512))
        archive.writestr("Metadata/top_1.png", png_bytes(512, 512))
        archive.writestr("Metadata/pick_1.png", png_bytes(512, 512))
        archive.writestr("Metadata/plate_3.png", png_bytes(128, 128))
        if sliced:
            archive.writestr("Metadata/plate_1.gcode", GCODE_1)
            archive.writestr("Metadata/plate_3.gcode", GCODE_3)
            archive.writestr(
                "Metadata/plate_1.gcode.md5",
                hashlib.md5(GCODE_1).hexdigest().upper(),
            )
            md5_3 = hashlib.md5(GCODE_3).hexdigest().upper()
            if bad_md5:
                md5_3 = "0" * 32
            archive.writestr("Metadata/plate_3.gcode.md5", md5_3)


def test_is_multi_plate_file() -> None:
    assert three_mf.is_multi_plate_file("part.gcode.3mf")
    assert three_mf.is_multi_plate_file("part.GCODE.3MF")
    assert not three_mf.is_multi_plate_file("part.3mf")
    assert not three_mf.is_multi_plate_file("part.gcode")


def test_parse_3mf(tmp_path: Path) -> None:
    archive_path = tmp_path / "part.gcode.3mf"
    build_archive(archive_path)

    metadata = three_mf.parse_3mf(archive_path)

    assert metadata["is_3mf"] is True
    assert metadata["sliced"] is True
    assert metadata["plate_count"] == 2
    assert metadata["slicer"] == "OrcaSlicer"
    assert metadata["slicer_version"] == "2.4.2"
    assert metadata["estimated_time"] == pytest.approx(579.0)
    assert metadata["filament_weight_total"] == pytest.approx(12.0)
    assert metadata["filament_type"] == '["PLA", "PETG"]'
    assert metadata["filament_colors"] == ["#FF0000", "#00FF00"]
    assert metadata["first_layer_extr_temp"] == pytest.approx(210.0)
    assert metadata["first_layer_bed_temp"] == pytest.approx(60.0)
    assert metadata["chamber_temp"] == pytest.approx(40.0)
    assert metadata["nozzle_diameter"] == pytest.approx(0.4)
    assert metadata["layer_height"] == pytest.approx(0.2)
    assert metadata["first_layer_height"] == pytest.approx(0.25)

    assert [plate["index"] for plate in metadata["plates"]] == [1, 3]
    first, third = metadata["plates"]
    assert first["name"] == "First plate"
    assert first["gcode_size"] == len(GCODE_1)
    assert first["gcode_md5"] == hashlib.md5(GCODE_1).hexdigest().upper()
    assert first["prediction"] == pytest.approx(123.0)
    assert first["weight"] == pytest.approx(4.5)
    assert first["object_count"] == 1
    assert first["printable"] is True
    assert third["name"] == "Third plate"
    assert third["support_used"] is True
    assert third["printable"] is True
    assert first["warnings"] == [
        {
            "message": "bed_temperature_too_high_than_filament",
            "level": 3,
            "code": "1000C001",
        }
    ]
    assert third["warnings"] == []

    first_thumbs = first["thumbnails"]
    assert any(thumb["type"] == "thumbnail" and thumb["width"] == 512 for thumb in first_thumbs)
    assert any(thumb["type"] == "thumbnail" and thumb["width"] == 32 for thumb in first_thumbs)
    assert any(thumb["type"] == "no_light" for thumb in first_thumbs)
    assert any(thumb["type"] == "top" for thumb in first_thumbs)
    assert any(thumb["type"] == "pick" for thumb in first_thumbs)
    for thumb in metadata["thumbnails"]:
        assert (tmp_path / thumb["relative_path"]).is_file()


def test_sparse_plate_indexes_and_extract(tmp_path: Path) -> None:
    archive_path = tmp_path / "part.gcode.3mf"
    build_archive(archive_path)

    assert three_mf.get_plate_indexes(archive_path) == [1, 3]
    plate_info = three_mf.get_plate_info(archive_path, 3)
    destination = tmp_path / "plate_3.gcode"
    result = three_mf.extract_plate(archive_path, 3, destination, plate_info)

    assert destination.read_bytes() == GCODE_3
    assert result["gcode_size"] == len(GCODE_3)
    assert result["gcode_md5"] == hashlib.md5(GCODE_3).hexdigest()


def test_extract_plate_md5_mismatch(tmp_path: Path) -> None:
    archive_path = tmp_path / "part.gcode.3mf"
    build_archive(archive_path, bad_md5=True)

    with pytest.raises(three_mf.ThreeMfError, match="MD5 mismatch"):
        three_mf.extract_plate(archive_path, 3, tmp_path / "plate_3.gcode")
    assert not (tmp_path / "plate_3.gcode").exists()


def test_unsliced_archive(tmp_path: Path) -> None:
    archive_path = tmp_path / "part.gcode.3mf"
    build_archive(archive_path, sliced=False)

    metadata = three_mf.parse_3mf(archive_path)
    assert metadata["sliced"] is False
    assert metadata["plate_count"] == 2
    assert metadata["plates"]
    assert all(not plate["printable"] for plate in metadata["plates"])
    assert three_mf.get_plate_indexes(archive_path) == []


def test_invalid_archive(tmp_path: Path) -> None:
    archive_path = tmp_path / "part.gcode.3mf"
    archive_path.write_bytes(b"not a zip archive")

    with pytest.raises(zipfile.BadZipFile):
        three_mf.parse_3mf(archive_path)
